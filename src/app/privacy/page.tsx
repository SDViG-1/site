function NumberedList({ items }: { items: [string, React.ReactNode][] }) {
  return (
    <ul className="flex flex-col gap-2.5">
      {items.map(([n, body], i) => (
        <li key={i} className="flex gap-3">
          <span className="shrink-0 font-semibold text-[#0a0a0c] tabular-nums">
            {n}
          </span>
          <span className="text-[#3f3f46]">{body}</span>
        </li>
      ))}
    </ul>
  );
}

